#!/usr/bin/env python3
"""Generate FilmPilot's sample film LUT ("FP Warm 400") as a .cube file.

A warm colour-negative look: warm white balance, gentle S-curve, lifted (faded) blacks,
softly rolled-off highlights, cool shadows / warm highlights, and slightly lower saturation.

Usage:  python3 tools/make_sample_lut.py [output.cube] [size]
Tweak the constants below to make your own looks, or export .cube files from Lightroom,
Resolve, Photoshop, etc., and drop them into app/src/main/assets/luts/.
"""
import sys

SIZE = 33
WARMTH_R, WARMTH_B = 1.06, 0.92   # white balance gains (linear light)
CONTRAST = 0.30                   # 0 = none, 1 = full smoothstep S-curve
BLACK_LIFT = 0.045                # faded film base
WHITE_POINT = 0.975               # highlight roll-off ceiling
SPLIT = 0.035                     # cool shadows / warm highlights amount
SATURATION = 0.86


def srgb_to_linear(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def linear_to_srgb(c):
    c = max(0.0, c)
    return c * 12.92 if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def clamp(x):
    return min(1.0, max(0.0, x))


def film(r, g, b):
    # White balance in linear light.
    r = linear_to_srgb(srgb_to_linear(r) * WARMTH_R)
    b = linear_to_srgb(srgb_to_linear(b) * WARMTH_B)
    r, g, b = clamp(r), clamp(g), clamp(b)

    # Tone curve per channel.
    def curve(x):
        s = x * x * (3 - 2 * x)
        x = x + CONTRAST * (s - x)
        return BLACK_LIFT + x * (WHITE_POINT - BLACK_LIFT)
    r, g, b = curve(r), curve(g), curve(b)

    # Split toning: teal shadows, warm highlights.
    l = 0.2126 * r + 0.7152 * g + 0.0722 * b
    t = (l - 0.5) * 2  # -1 shadows .. +1 highlights
    r += SPLIT * t
    g += SPLIT * 0.3 * t
    b -= SPLIT * t

    # Saturation around luma.
    l = 0.2126 * r + 0.7152 * g + 0.0722 * b
    r = l + (r - l) * SATURATION
    g = l + (g - l) * SATURATION
    b = l + (b - l) * SATURATION
    return clamp(r), clamp(g), clamp(b)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "app/src/main/assets/luts/fp_warm_400.cube"
    size = int(sys.argv[2]) if len(sys.argv) > 2 else SIZE
    n = size - 1
    with open(out, "w") as f:
        f.write('TITLE "FP Warm 400"\n')
        f.write("# Generated by tools/make_sample_lut.py\n")
        f.write(f"LUT_3D_SIZE {size}\n")
        f.write("DOMAIN_MIN 0.0 0.0 0.0\nDOMAIN_MAX 1.0 1.0 1.0\n")
        for bi in range(size):          # blue slowest
            for gi in range(size):
                for ri in range(size):  # red fastest
                    r, g, b = film(ri / n, gi / n, bi / n)
                    f.write(f"{r:.6f} {g:.6f} {b:.6f}\n")
    print(f"wrote {out} ({size}^3 entries)")


if __name__ == "__main__":
    main()
